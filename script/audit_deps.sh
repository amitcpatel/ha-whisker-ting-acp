#!/usr/bin/env bash
# Reproducible dependency audit for the whisker_ting integration.
#
# Resolves the integration's runtime closure (manifest requirements plus
# aiohttp, which Home Assistant core provides) under the exact Home Assistant
# package constraints in requirements/, then runs pip-audit on that closure.
#
# Usage: script/audit_deps.sh           # check: fail if closure drifted or has advisories
#        script/audit_deps.sh --update  # rewrite requirements/audit-closure.txt
#
# Needs: uv (https://docs.astral.sh/uv/). Uses Python 3.14 to match HA 2026.10.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
HA_VERSION="2026.10.2"
CONSTRAINTS="$ROOT/requirements/ha-${HA_VERSION}-constraints.txt"
CLOSURE="$ROOT/requirements/audit-closure.txt"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

REQS=$(python3 -c 'import json,sys; print("\n".join(json.load(open(sys.argv[1]))["requirements"]))' \
  "$ROOT/custom_components/whisker_ting/manifest.json")

uv venv -q -p 3.14 "$WORK/venv"
# shellcheck disable=SC2086
uv pip install -q -p "$WORK/venv/bin/python" -c "$CONSTRAINTS" aiohttp $REQS
uv pip freeze -p "$WORK/venv/bin/python" > "$WORK/freeze.txt"

{
  echo "# Resolved runtime closure of this integration under Home Assistant ${HA_VERSION}."
  echo "# Generated by script/audit_deps.sh: manifest requirements + aiohttp (provided by HA core),"
  echo "# resolved with -c requirements/ha-${HA_VERSION}-constraints.txt. Do not edit by hand."
  cat "$WORK/freeze.txt"
} > "$WORK/closure.txt"

if [[ "${1:-}" == "--update" ]]; then
  cp "$WORK/closure.txt" "$CLOSURE"
  echo "updated $CLOSURE"
elif ! diff -u "$CLOSURE" "$WORK/closure.txt"; then
  echo "requirements/audit-closure.txt is out of date; run script/audit_deps.sh --update" >&2
  exit 1
fi

uvx pip-audit -r "$WORK/freeze.txt" --no-deps --disable-pip --progress-spinner off
